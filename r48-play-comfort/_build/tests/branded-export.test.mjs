import assert from 'node:assert/strict';
import fs from 'node:fs';
import z from 'node:zlib';
import {deckYdk,presetFor,renderDeck} from '../dist/deck-list.mjs';
import {nov08Brain} from '../dist/ai/brain/branded-brain.mjs';
import {parseYdk} from '../dist/windbot/edo.mjs';
import {openingPlan} from '../dist/game-plans.mjs';
import {validateDeck} from '../dist/deck-validator.mjs';
const read=f=>JSON.parse(fs.readFileSync('dist/'+f));
const unzip=f=>JSON.parse(z.gunzipSync(fs.readFileSync('dist/'+f)));
const original=read('decks.json').decks.find(d=>d.id==='branded');
const draft=presetFor(original,'tcg-2026-10-19'),cards=read('deck-cards.json').cards,ban=read('banlists/tcg-2026-10-19.json');
const y=deckYdk(draft);assert.deepEqual(parseYdk(y),JSON.parse(fs.readFileSync('approved.json')));
assert.ok(validateDeck(draft,unzip('cards.json.gz'),ban,{scripts:unzip('scripts.json.gz'),exactSizes:{main:41,extra:15,side:15}}).ok);
assert.ok(Object.values(parseYdk(y)).flat().every(id=>cards[id]?.name));
const html=renderDeck(draft,cards,ban,await nov08Brain());
assert.match(html,/Main Deck <b>41/);assert.match(html,/Extra Deck <b>15/);assert.match(html,/Side Deck <b>15/);
assert.match(html,/Springans Kitt/);assert.match(html,/Tri-Brigade Springans Kitt|Branded in White|Dogmatika Ecclesia/);assert.doesNotMatch(html,/Red-Eyes Dark Dragoon|Dogmatika Fleurdelis|Fusion Deployment|Branded Lost/);
assert.doesNotMatch(JSON.stringify(openingPlan({decks:[draft],zone:()=>[],name:()=>'',order:[0]},0)),/Dragoon/);
const white=openingPlan({decks:[draft],zone:()=>[{code:73819701}],name:()=> 'Fallen of the White Dragon',order:[0]},0);
assert.equal(white.line[0],'Fallen of the White Dragon');
assert.doesNotMatch(JSON.stringify(white.line),/Aluber/);
fs.writeFileSync('Branded-MetaGamesGX-41.ydk',y);
console.log('(M) Branded 41 approved export, rendered deck viewer and scoped teaching plan: PASS');
